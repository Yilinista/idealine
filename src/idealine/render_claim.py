def _highlight(context: str, evidence: str, verified: bool) -> str:
    safe = html.escape(context)
    if evidence and verified:
        idx = context.lower().find(evidence.strip().lower())
        if idx >= 0:
            end = idx + len(evidence.strip())
            return (
                html.escape(context[:idx])
                + "<mark>" + html.escape(context[idx:end]) + "</mark>"
                + html.escape(context[end:])
            )
    return safe


def to_html(t: Timeline) -> str:
    e_ = html.escape
    seed = t.seed
    body = [
        f"<h1>{e_(t.claim)}</h1>",
        f'<p class="meta">Seed paper: <a href="{e_(seed.url or "")}">{e_(seed.title)}</a> '
        f"({e_(seed.short_authors)}, {seed.year or 'n.d.'})</p>",
        f'<p class="summary">{e_(_summary_line(t))}</p>',
    ]
    if t.classified:
        body.append(
            f'<p class="notice">Stance labels were generated by <code>{e_(t.model or "")}</code> from the '
            "citing sentence alone. They can be wrong: read the quote before relying on a label.</p>"
        )
        counts = stance_counts(t)
        boxes = "".join(
            f'<label><input type="checkbox" value="{s}" checked> {STANCE_LABEL[s]} ({counts[s]})</label>'
            for s in STANCE_ORDER
            if counts[s]
        )
        body.append(f'<div class="filters">{boxes}</div>')

    year = object()
    for c in visible_entries(t):
        if c.paper.year != year:
            year = c.paper.year
            body.append(f"<h2>{year or 'Undated'}</h2>")
        cls = c.stance or "cites"
        label = STANCE_LABEL.get(c.stance, "Cites")
        parts = [
            f'<div class="entry {cls}">',
            f'<div class="tag">{e_(label)}</div>',
            f'<a href="{e_(c.paper.url or "")}">{e_(c.paper.title)}</a> '
            f'<span class="meta">{e_(c.paper.short_authors)}, {e_(_date(c))}</span>',
        ]
        if c.note:
            parts.append(f"<div>{e_(c.note)}</div>")
        parts.append(f"<blockquote>{_highlight(c.context, c.evidence, c.evidence_verified)}</blockquote>")
        if c.evidence and not c.evidence_verified:
            parts.append('<div class="warn">The model\'s evidence span was not found verbatim in the quote.</div>')
        parts.append("</div>")
        body.append("".join(parts))

    body.append(
        '<footer><p>Generated by <a href="https://github.com/Yilinista/idealine">idealine</a> '
        "from Semantic Scholar citation data.</p></footer>"
    )
    return (
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>Claim timeline: {e_(t.claim[:60])}</title><style>{_CSS}</style></head>"
        f"<body><main>{''.join(body)}</main><script>{_JS}</script></body></html>\n"
    )
