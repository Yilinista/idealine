"""Render a timeline as Markdown and as one self-contained HTML file."""

from __future__ import annotations

import html
from collections import Counter

from .models import Candidate, Timeline

STANCE_LABEL = {
    "supports": "Supports",
    "refutes": "Refutes",
    "refines": "Refines",
    "mentions": "Mentions",
    None: "Cites",
}
STANCE_ORDER = ["refutes", "refines", "supports", "mentions"]


def visible_entries(t: Timeline) -> list[Candidate]:
    """Date-sorted entries, minus ones the model judged unrelated."""
    entries = [e for e in t.entries if e.stance != "unrelated"]
    return sorted(entries, key=lambda e: (e.paper.sort_key, e.paper.title))


def stance_counts(t: Timeline) -> Counter:
    return Counter(e.stance for e in visible_entries(t))


def _summary_line(t: Timeline) -> str:
    shown = visible_entries(t)
    fetched = f"{t.total_citations} citing papers fetched"
    if t.papers_available and t.papers_available > t.total_citations:
        fetched = (
            f"{t.total_citations} of {t.papers_available} citing papers sampled evenly across time"
        )
    parts = [
        fetched,
        f"{t.citations_without_context} had no citing sentence in Semantic Scholar",
        f"{len(t.entries)} sentences ranked",
        f"{len(shown)} shown",
    ]
    if t.classified:
        counts = stance_counts(t)
        parts.append(", ".join(f"{counts[s]} {s}" for s in STANCE_ORDER if counts[s]) or "no labels")
    return "; ".join(parts) + "."


def _date(c: Candidate) -> str:
    return c.paper.publication_date or (str(c.paper.year) if c.paper.year else "n.d.")


def to_markdown(t: Timeline) -> str:
    seed = t.seed
    out = [
        f"# Claim timeline: {t.claim}",
        "",
        f"Seed paper: [{seed.title}]({seed.url}) ({seed.short_authors}, {seed.year or 'n.d.'})",
        "",
        _summary_line(t),
        "",
    ]
    if t.classified:
        out += [
            f"> Stance labels were generated by `{t.model}` from the citing sentence alone. "
            "They can be wrong: read the quote before relying on a label.",
            "",
        ]
    else:
        out += ["> Run without `--no-llm` to label each step as supports / refutes / refines.", ""]

    year = None
    for e in visible_entries(t):
        if e.paper.year != year:
            year = e.paper.year
            out += [f"## {year or 'Undated'}", ""]
        label = STANCE_LABEL.get(e.stance, e.stance or "Cites")
        out.append(f"- **{label}**: [{e.paper.title}]({e.paper.url}) ({e.paper.short_authors}, {_date(e)})")
        if e.note:
            out.append(f"  - {e.note}")
        out.append(f"  - > {e.context}")
        if e.evidence and not e.evidence_verified:
            out.append("  - Warning: the model's evidence span was not found verbatim in the quote.")
    out += ["", "Generated by [idealine](https://github.com/Yilinista/idealine).", ""]
    return "\n".join(out)


