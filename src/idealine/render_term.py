def to_data(t: TermTimeline) -> dict:
    by_id = t.evidence_by_id()

    def ev(ids):
        out = []
        for i in ids:
            e = by_id.get(i)
            if e:
                out.append({"id": i, "text": e.text, "title": e.work.title, "year": e.work.year, "date": e.work.date,
                            "url": e.work.url, "authors": e.work.short_authors, "fromTitle": e.from_title,
                            "field": e.work.field_name, "inSet": e.work.in_set, "sense": e.sense})
        return out

    return {
        "term": t.term,
        "aliases": t.aliases,
        "summary": t.summary,
        "counts": [[y, c] for y, c in t.counts.items()],
        "quarters": [[k, c] for k, c in t.quarters],
        "undated": [[y, c] for y, c in t.undated],
        # Every year from the first to the last count, so gap years have a total too.
        "totals": [[y, t.totals[y]] for y in range(min(t.counts), max(t.counts) + 1) if y in t.totals] if t.counts else [],
        "totalsAsOf": t.totals_asof if t.totals else "",
        "roots": t.roots,
        # Every quoted sentence, for the evidence lane under the chart.
        "quotes": ev([e.eid for e in t.evidence]),
        "total": t.total,
        "model": t.model,
        "generated": t.generated,
        "lang": t.lang,
        "meaning": t.meaning,
        "focus": t.focus,
        "otherSenses": [{"label": s.label, "meaning": s.meaning, "evidence": ev(s.evidence)} for s in t.other_senses],
        "senses": [{"key": s.key, "label": s.label, "definition": s.meaning, "related": s.related} for s in t.senses],
        "evidenceCount": len(t.evidence),
        "eras": [{"start": e.start_year, "end": e.end_year, "label": e.label, "meaning": e.meaning,
                  "evidence": ev(e.evidence)} for e in t.eras],
        "milestones": [{
            "year": m.year, "kind": m.kind, "title": m.title, "why": m.why,
            "url": m.work.url if m.work else None,
            "date": m.work.date if m.work else None,
            "workTitle": m.work.title if m.work else None,
            "authors": m.work.short_authors if m.work else None,
            "link": m.link_status, "evidence": ev(m.evidence),
            "checks": {"inSense": m.in_sense, "coinage": m.coinage} if m.in_sense is not None or m.coinage is not None else None,
            "shift": m.shift,
        } for m in t.milestones],
    }


def to_markdown(t: TermTimeline) -> str:
    by_id = t.evidence_by_id()
    out = [f"# {t.term}: where it came from", ""]
    if t.summary:
        out += [t.summary, ""]
    span = f"{min(t.counts)}–{max(t.counts)}" if t.counts else "n/a"
    out += [f"{t.total} papers in OpenAlex use this term ({span}); {len(t.evidence)} sentences read.", ""]
    if t.focus and t.other_senses:
        out += [f"Follows: {t.focus}", "", "## Same words, other meanings (left out)", ""]
        for s in t.other_senses:
            out.append(f"- **{s.label}**: {s.meaning} ({len(s.evidence)} quotes)")
        out.append("")
    if t.eras:
        out += ["## Eras", ""]
        for e in t.eras:
            out.append(f"- **{e.start_year}–{e.end_year} · {e.label}**: {e.meaning}")
        out.append("")
    out += ["## Milestones", ""]
    for m in t.milestones:
        title = f"[{m.title}]({m.work.url})" if m.work and m.work.url else m.title
        out.append(f"- **{m.year} · {m.kind}**: {title}. {m.why}")
        for i in m.evidence[:2]:
            e = by_id.get(i)
            if e:
                out.append(f"  - > {e.text} ({e.work.short_authors}, {e.work.year})")
    if t.model:
        out += ["", f"> Eras and milestones were proposed by `{t.model}` from the quoted sentences only. Check the quotes."]
    out += ["", f"Generated by [idealine]({REPO_URL}) from OpenAlex data.", ""]
    return "\n".join(out)


